"""Write docs/drill-rescue/ASSET-PROVENANCE.md from the pipeline's own records.

Usage: python3 art/write_provenance.py
Reads art/ledger/polyhaven-download-ledger.json (what was downloaded, with MD5s)
and client/src/world/assets/{sky,textures,props,vegetation}.json (what was made).
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
A = ROOT / "client/src/world/assets"
ledger = {e["id"]: e for e in json.loads((ROOT / "art/ledger/polyhaven-download-ledger.json").read_text())}
sky = json.loads((A / "sky.json").read_text())
tex = json.loads((A / "textures.json").read_text())
props = json.loads((A / "props.json").read_text())
veg = json.loads((A / "vegetation.json").read_text())


def src(pid):
    e = ledger[pid]
    files = ", ".join(f"`{f['file']}` ({f['bytes']//1024} KB, md5 `{f.get('md5') or '—'}`)" for f in e["files"][:3])
    more = f" + {len(e['files']) - 3} more" if len(e["files"]) > 3 else ""
    return e, files + more


out = ["# Asset provenance", "",
       "Every runtime asset of the 3D world is either **original** (generated by code in this",
       "repository) or derived from **Poly Haven** assets released under **CC0 1.0**",
       "(<https://polyhaven.com/license>: “You can use our assets for any purpose, including",
       "commercial work … redistribute them … include them when sharing your own work”;",
       "attribution not required, given below anyway). Nothing is fetched at runtime: all",
       "files are bundled by Vite and precached for offline use. The notice",
       "`client/public/licenses/POLYHAVEN-CC0.txt` ships in the build.", "",
       "Regenerate everything from the sources with the scripts in `art/` (commands in",
       "`docs/drill-rescue/HANDOFF.md` §5). Source downloads are not committed; the ledger",
       "`art/ledger/polyhaven-download-ledger.json` records each source file and its MD5.", "",
       "## Skies", "",
       "| Output | Source (CC0) | Authors | Processing | Size |", "|---|---|---|---|---|"]
for name, s in sky["skies"].items():
    pid = s["source"]
    e, files = src(pid)
    out.append(f"| `{name}.webp` {s['width']}×{s['height']} | [{pid}]({e['url']}) — {files} | {', '.join(e['authors'])} | tone-mapped (exposure {s['exposure']}, ACES fit), elevation −5°…+90° kept, WebP q80 (`art/process_sky.py`); {'sun elevation measured' if name == 'sky-day' else 'brightest region (horizon town glow) at'} {s['sun']['elevation_deg']}° | {s['bytes']//1024} KB |")
out += ["", "## PBR textures", "", "| Output prefix | Source (CC0) | Authors | Maps → output | Size |", "|---|---|---|---|---|"]
for name, t in tex.items():
    pid = t["source"].rsplit("/", 1)[1]
    e, files = src(pid)
    maps = ", ".join(f"{k} {v['size']}px" for k, v in t["files"].items())
    total = sum(v["bytes"] for v in t["files"].values())
    out.append(f"| `{name}-*` | [{pid}]({e['url']}) | {', '.join(e['authors'])} | {maps}; Lanczos resize, WebP (`art/process_textures.py`) | {total//1024} KB |")
out += ["", "## Props (decimated photoscans)", "", "| Output | Source (CC0) | Authors | Source → output triangles | Textures | Size |", "|---|---|---|---|---|---|"]
for name, p in props.items():
    pid = p["source"].rsplit("/", 1)[1]
    e, _ = src(pid)
    out.append(f"| `{name}.glb` | [{pid}]({e['url']}) | {', '.join(e['authors'])} | {p['source_triangles']:,} → {p['triangles']:,} (Blender collapse decimation, `art/blender_props.py`) | {p['texture']} px WebP | {p['bytes']//1024} KB |")
out += ["", "## Vegetation impostors", "",
        f"`vegetation-atlas.webp` ({veg['bytes']//1024} KB, 2048×1024 RGBA) holds orthographic Cycles renders",
        "of these CC0 scans (`art/blender_impostors.py`, `art/build_vegetation_atlas.py`):", "",
        "| Cell | Source (CC0) | Authors | Card size |", "|---|---|---|---|"]
for name, c in veg["cells"].items():
    pid = {"tree-jacaranda": "jacaranda_tree", "tree-island": "island_tree_02", "shrub-rooibos": "wild_rooibos_bush", "shrub-broad": "shrub_04"}[name.rsplit("-", 1)[0] if not name.endswith(("side-a", "side-b")) else name[: -len("-side-a")]]
    e, _ = src(pid)
    out.append(f"| `{name}` | [{pid}]({e['url']}) | {', '.join(e['authors'])} | {c['width_m']} × {c['height_m']} m |")
out += ["", "Downloaded but not used: `dead_tree_trunk_02` (a fallen log, not a standing tree).", "",
        "## Original work (this repository)", "",
        "| Asset | Made by | Notes |", "|---|---|---|",
        "| Facility architecture (buildings, hangar, containers, towers, masts, generator, fuel, helipad, lamps, gate, tents, houses, warehouse, bunker, sensor mast, fence/HESCO/sandbag lines, occluder dressing) | `client/src/world/kit.ts` | procedural geometry, metric UVs, vertex tints, merged per material |",
        "| Terrain, layouts | `client/src/world/terrain.ts`, `layout.ts` | deterministic value noise; flat within 1 700 m |",
        "| Splat map, HESCO mesh, chain-link, lamp light pools | `client/src/world/procedural-textures.ts` | drawn on a canvas at runtime |",
        "| Thermal appearance | `client/src/world/thermal.ts` | illustrative index → palette mapping, not radiometry |",
        "| Opening hero image | `client/src/premium/media/` | team concept image, owner-approved 2026-10-15 (see its PROVENANCE.md) |", "",
        "## Rejected sources", "",
        "Sketchfab, BlenderKit, Poly Pizza, CGTrader and Quaternius were inspected and not used",
        "(licence, redistribution, identity-leak and style reasons: `RESEARCH-AND-ASSET-SELECTION.md` §2–3).",
        "No game-ripped, paid, non-commercial or no-derivatives asset is in the repository."]
total = sum(f.stat().st_size for f in A.iterdir() if f.suffix in (".webp", ".glb"))
out += ["", f"Total bundled world assets: {total/1048576:.2f} MB ({len([f for f in A.iterdir() if f.suffix in ('.webp', '.glb')])} files)."]
(ROOT / "docs/drill-rescue/ASSET-PROVENANCE.md").write_text("\n".join(out) + "\n")
print("written", total)
