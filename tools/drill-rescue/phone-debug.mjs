import { newTab, sleep } from './drill.mjs';
const APP = process.argv[2];
const c = await newTab(390, 844);
const setSelect = (label, pred) => c.ev(`(() => { const s = document.querySelector('select[aria-label=${JSON.stringify(label)}]'); const o = [...s.options].find(o => (${pred})(o)); const set = Object.getOwnPropertyDescriptor(HTMLSelectElement.prototype, 'value').set; set.call(s, o.value); s.dispatchEvent(new Event('change', { bubbles: true })); return o.text; })()`);
await c.nav(APP + '/'); await sleep(1500);
await setSelect('Drill', "o => o.value === 'adaptive'"); await sleep(600);
await c.clickButton('Prepare adaptive drill'); await c.waitFor(`!!(${c.button('Start adaptive drill')})`, 30000); await c.clickButton('Start adaptive drill');
await sleep(6000);
await c.clickEl(`document.querySelector('.contact-list .contact-item:not(.stale)')`); await sleep(1500);
const info = await c.ev(`(() => { const b = [...document.querySelectorAll('.guided button')].find(b => b.innerText.trim().startsWith('Designate')); b.scrollIntoView({block:'nearest'}); const r = b.getBoundingClientRect(); const x = r.x + r.width/2, y = r.y + r.height/2; const hit = document.elementFromPoint(x, y); return { x, y, vh: innerHeight, disabled: b.disabled, hit: hit && (hit.className || hit.tagName) + ' / ' + (hit.closest('button')?.innerText || ''), same: hit && b.contains(hit) }; })()`);
console.log(JSON.stringify(info));
await c.click(info.x, info.y); await sleep(800);
console.log(await c.ev(`document.querySelector('.guided-status')?.innerText`));
const OUT = process.argv[3];
const radio = v => c.clickEl(`document.querySelector('.guided input[type=radio][value=${v}]')?.closest('label')`);
await radio('quad'); await sleep(200); await radio('hostile'); await sleep(300);
await c.ev(`document.querySelector('.decision-workspace').scrollIntoView({block:'start'})`); await sleep(300);
await c.snap(OUT + '/phone-classify.png');
await c.clickEl(`[...document.querySelectorAll('.guided button')].find(b => b.innerText.includes('Confirm classification'))`); await sleep(800);
await c.ev(`document.querySelector('.decision-workspace').scrollIntoView({block:'start'})`); await sleep(300);
await c.snap(OUT + '/phone-respond.png');
console.log(await c.ev(`document.querySelector('.guided-status')?.innerText`));
await c.closeTab();
